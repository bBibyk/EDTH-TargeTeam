"""Design the 64 kHz -> 32 kHz decimation FIR for mic_stream and write fir_coeffs.h.

Stage 1 (DFSDM hardware): PDM 1.6 MHz -> sinc5, FOSR 25 -> 64 kHz.
Stage 2 (this FIR, on the M4F): low-pass that also undoes the sinc5 droop,
then keep every 2nd sample -> 32 kHz.
Run:  python tools/design_fir.py   (needs numpy)
"""
import numpy as np
from pathlib import Path

F_PDM, FOSR, ORDER = 1.6e6, 25, 5
FS1 = F_PDM / FOSR                     # 64 kHz
NTAPS = 64
PASS, STOP = 14000.0, 18000.0

def sinc_n(f):
    x = np.pi * f / F_PDM
    with np.errstate(invalid="ignore", divide="ignore"):
        h = np.where(f == 0, 1.0, np.sin(FOSR * x) / (FOSR * np.sin(x)))
    return np.abs(h) ** ORDER

f = np.linspace(0, FS1 / 2, 4000)
band_p, band_s = f <= PASS, f >= STOP
target = np.zeros_like(f); target[band_p] = 1.0 / sinc_n(f[band_p])
weight = np.zeros_like(f); weight[band_p] = 1.0; weight[band_s] = 30.0

# Linear-phase, even length (type II): h symmetric, H(f) = sum 2 h[k] cos(2 pi f (k - (N-1)/2) / fs)
half = NTAPS // 2
k = np.arange(half)
A = 2 * np.cos(2 * np.pi * np.outer(f, (half - 0.5 - k)) / FS1)
sel = weight > 0
coef, *_ = np.linalg.lstsq(A[sel] * weight[sel, None], target[sel] * weight[sel], rcond=None)
h = np.concatenate([coef, coef[::-1]])

def response(freqs):
    n = np.arange(NTAPS)
    return np.abs(np.exp(-2j * np.pi * np.outer(freqs, n) / FS1) @ h)

fp = np.linspace(20, PASS, 500)
total = response(fp) * sinc_n(fp)
fs_ = np.linspace(STOP, FS1 / 2, 500)
print(f"taps {NTAPS}, sum {h.sum():.4f}")
print(f"passband 20 Hz-14 kHz, sinc5 x FIR: {20*np.log10(total.min()):+.2f} .. {20*np.log10(total.max()):+.2f} dB")
print(f"sinc5 alone at 8/12/14 kHz: " + ", ".join(f"{20*np.log10(sinc_n(np.array([x]))[0]):+.1f}" for x in (8e3, 12e3, 14e3)) + " dB")
print(f"stopband >= 18 kHz: {20*np.log10(response(fs_).max()):.1f} dB")
for x in (15e3, 16e3, 17e3):
    print(f"  at {x/1e3:.0f} kHz: {20*np.log10(response(np.array([x]))[0]*sinc_n(np.array([x]))[0]):+.1f} dB")
# alias rejection of stage 1: worst sinc5 gain at 64k*m +- f for f in passband, m=1..
worst = max(sinc_n(np.array([m * FS1 - x, m * FS1 + x])).max() for m in range(1, 13) for x in np.linspace(0, PASS, 50))
print(f"stage-1 alias rejection into 0-14 kHz: {20*np.log10(worst):.1f} dB")

out = Path(__file__).resolve().parents[1] / "src" / "fir_coeffs.h"
out.parent.mkdir(exist_ok=True)
body = ",\n".join("    " + ", ".join(f"{v: .9e}f" for v in h[i:i + 4]) for i in range(0, NTAPS, 4))
out.write_text(
    "/* Generated by tools/design_fir.py - do not edit by hand.\n"
    f" * 64 kHz -> 32 kHz decimation FIR, {NTAPS} taps, passband 0-{PASS/1e3:.0f} kHz with sinc5 (FOSR {FOSR})\n"
    f" * droop compensation, stopband >= {STOP/1e3:.0f} kHz. */\n"
    "#pragma once\n"
    f"#define FIR_NTAPS {NTAPS}\n"
    "static const float fir_coeffs[FIR_NTAPS] = {\n" + body + "\n};\n")
print("wrote", out)
